//! Creating a new file in a Finder folder.
//!
//! The name is localized and collision-safe: the first attempt is "Untitled.<ext>", then
//! "Untitled 2.<ext>" and so on. Creation uses O_EXCL, so a name that appears between the check and
//! the write is retried instead of overwriting the existing file.
//!
//! Text types are created empty. Office types cannot be: a .docx/.xlsx/.pptx is a zip package, and
//! an empty file with that extension is a file Word, Excel and PowerPoint refuse to open. Those are
//! copies of the blank packages in `assets/finder-templates/`, embedded at build time so a template
//! cannot go missing from a hand-assembled bundle.

use std::io::{ErrorKind, Write};
use std::path::{Path, PathBuf};

use crate::i18n::t;

/// The blank package copied in for `extension`, or `None` for a type whose empty file is the
/// document. Generated by `assets/finder-templates/generate.py`.
fn template(extension: &str) -> Option<&'static [u8]> {
    match extension {
        "docx" => Some(include_bytes!("../../assets/finder-templates/blank.docx")),
        "xlsx" => Some(include_bytes!("../../assets/finder-templates/blank.xlsx")),
        "pptx" => Some(include_bytes!("../../assets/finder-templates/blank.pptx")),
        _ => None,
    }
}

/// Create a new file of `extension` inside `directory`. The caller has already verified the
/// directory and that the extension is one the config offers.
pub(crate) fn create_in(directory: &Path, extension: &str) -> std::io::Result<PathBuf> {
    if !directory.is_dir() {
        return Err(std::io::Error::new(
            ErrorKind::NotFound,
            "target directory does not exist",
        ));
    }
    let base = t("finder_menu.untitled");
    // Finder's own numbering: "Untitled.md", then "Untitled 2.md", "Untitled 3.md" (it never
    // creates "Untitled 1").
    for suffix in 0..1000u32 {
        let name = if suffix == 0 {
            format!("{base}.{extension}")
        } else {
            format!("{base} {}.{extension}", suffix + 1)
        };
        let path = directory.join(name);
        match std::fs::OpenOptions::new()
            .write(true)
            .create_new(true)
            .open(&path)
        {
            Ok(mut file) => {
                if let Some(bytes) = template(extension) {
                    // A package that cannot be written leaves nothing behind: a half-written or
                    // empty .docx looks like a document until the user opens it.
                    if let Err(error) = file.write_all(bytes) {
                        drop(file);
                        let _ = std::fs::remove_file(&path);
                        return Err(error);
                    }
                }
                file.flush()?;
                return Ok(path);
            }
            Err(error) if error.kind() == ErrorKind::AlreadyExists => continue,
            Err(error) => return Err(error),
        }
    }
    Err(std::io::Error::new(
        ErrorKind::AlreadyExists,
        "too many files named like the new file",
    ))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn first_file_is_untitled_with_the_extension() {
        let directory = tempfile::tempdir().expect("tempdir");
        let path = create_in(directory.path(), "md").expect("create");
        assert_eq!(
            path.file_name().unwrap().to_string_lossy(),
            format!("{}.md", t("finder_menu.untitled"))
        );
        assert_eq!(std::fs::metadata(&path).unwrap().len(), 0);
    }

    #[test]
    fn collisions_get_a_number_suffix() {
        let directory = tempfile::tempdir().expect("tempdir");
        let base = t("finder_menu.untitled");
        std::fs::write(directory.path().join(format!("{base}.md")), b"existing").unwrap();
        let path = create_in(directory.path(), "md").expect("create");
        assert_eq!(
            path.file_name().unwrap().to_string_lossy(),
            format!("{base} 2.md")
        );
    }

    #[test]
    fn a_missing_directory_is_an_error() {
        let directory = tempfile::tempdir().expect("tempdir");
        let missing = directory.path().join("missing");
        assert!(create_in(&missing, "md").is_err());
    }

    #[test]
    fn office_files_are_copies_of_the_bundled_template() {
        let directory = tempfile::tempdir().expect("tempdir");
        for extension in ["docx", "xlsx", "pptx"] {
            let path = create_in(directory.path(), extension).expect("create");
            let written = std::fs::read(&path).expect("read back");
            let expected = template(extension).expect("a bundled template");
            assert_eq!(written, expected, "{extension} is not the bundled template");
            // A package is a zip archive; an empty file would fail here and in Office.
            assert!(
                written.starts_with(b"PK\x03\x04"),
                "{extension} is not a zip package"
            );
        }
    }

    /// A type the menu offers must be a plain text file that is empty by definition, or carry a
    /// template. An advertised package type with no template would create an empty .docx, which
    /// looks like a document until the user opens it.
    #[test]
    fn no_advertised_type_is_created_as_a_broken_package() {
        const PLAIN_TEXT: [&str; 3] = ["md", "txt", "json"];
        for extension in crate::config::FINDER_MENU_FILE_TYPES {
            assert!(
                PLAIN_TEXT.contains(&extension) || template(extension).is_some(),
                "{extension} has neither a template nor an empty-file meaning"
            );
        }
    }
}
